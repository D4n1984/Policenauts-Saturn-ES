"""Pruebas con contenido sintetico, nunca con discos del Vault.

XDELTA3 debe apuntar al ejecutable instalado localmente.
Los artefactos de prueba se conservan; no se borra ningun archivo.
"""
import json
import os
from pathlib import Path
import random
import subprocess
import tempfile
import unittest
from unittest.mock import patch

import patcher


class PatcherTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        executable = os.environ.get("XDELTA3")
        if not executable or not Path(executable).is_file():
            raise RuntimeError("Definir XDELTA3 con la ruta al ejecutable para probar el flujo real")
        cls.xdelta = Path(executable)
        cls.root = Path(tempfile.mkdtemp(prefix="policenauts_patcher_tests_"))
        print(f"\nArtefactos conservados: {cls.root}")

    def setUp(self):
        self.folder = self.root / self._testMethodName
        self.folder.mkdir()
        self.source = self.folder / "base.bin"
        self.target = self.folder / "translated.bin"
        raw = random.Random(20261110).randbytes(200000)
        self.source.write_bytes(raw)
        self.target.write_bytes(raw[:35000] + b"synthetic Spanish test" * 71 + raw[39000:] + b"end")
        self.delta = self.folder / "translation.xdelta"
        subprocess.run([str(self.xdelta), "-e", "-s", str(self.source),
                        str(self.target), str(self.delta)], check=True, capture_output=True)
        self.manifest = self.folder / "manifest.json"
        self.data = {"format": "verified-xdelta-v1", "platform": "Sega Saturn",
                     "status": "experimental", "label": "Synthetic test only",
                     "base_description": "Synthetic bytes; not a game",
                     "source": patcher.describe(self.source),
                     "patch": {"name": self.delta.name, **patcher.describe(self.delta)},
                     "target": {"name": "output.bin", **patcher.describe(self.target)}}
        patcher.write_new_json(self.manifest, self.data)
        self.output = self.folder / "result"

    def rewrite_manifest(self):
        # This is exclusively a synthetic fixture generated by this test.
        self.manifest.write_text(json.dumps(self.data), encoding="utf-8")

    def apply(self):
        return patcher.apply(self.manifest, self.source, self.output, self.xdelta, True)

    def test_real_roundtrip_and_original_unchanged(self):
        digest = patcher.sha256(self.source)
        result = self.apply()
        self.assertEqual(result.read_bytes(), self.target.read_bytes())
        self.assertEqual(patcher.sha256(self.source), digest)
        self.assertTrue((self.output / "VERIFICADO.json").is_file())

    def test_wrong_base_rejected_before_creating_output(self):
        self.source.write_bytes(b"wrong synthetic base")
        with self.assertRaisesRegex(patcher.PatchError, "Base incompatible"):
            self.apply()
        self.assertFalse(self.output.exists())

    def test_corrupt_patch_rejected_before_creating_output(self):
        self.delta.write_bytes(b"bad synthetic patch")
        with self.assertRaisesRegex(patcher.PatchError, "Parche incompatible"):
            self.apply()
        self.assertFalse(self.output.exists())

    def test_wrong_target_hash_retains_unverified_output(self):
        self.data["target"]["sha256"] = "0" * 64
        self.rewrite_manifest()
        with self.assertRaisesRegex(patcher.PatchError, "Salida incorrecta"):
            self.apply()
        self.assertTrue((self.output / "resultado.partial").exists())
        self.assertTrue((self.output / "FALLO.json").exists())
        self.assertFalse((self.output / "output.bin").exists())

    def test_existing_output_directory_untouched(self):
        self.output.mkdir()
        sentinel = self.output / "keep.bin"
        sentinel.write_bytes(b"preserve")
        with self.assertRaises(FileExistsError):
            self.apply()
        self.assertEqual(sentinel.read_bytes(), b"preserve")

    def test_paths_cannot_escape_manifest_directory(self):
        self.data["patch"]["name"] = "../translation.xdelta"
        self.rewrite_manifest()
        with self.assertRaises(patcher.PatchError):
            self.apply()
        self.assertFalse(self.output.exists())

    def test_experimental_needs_explicit_flag(self):
        with self.assertRaisesRegex(patcher.PatchError, "experimental"):
            patcher.apply(self.manifest, self.source, self.output, self.xdelta)
        self.assertFalse(self.output.exists())

    def test_xdelta_failure_preserves_diagnostic(self):
        # Valid hash, invalid VCDIFF contents: must fail inside the external decoder.
        self.delta.write_bytes(b"This is not a VCDIFF file")
        self.data["patch"].update(patcher.describe(self.delta))
        self.rewrite_manifest()
        with self.assertRaisesRegex(patcher.PatchError, "xdelta3"):
            self.apply()
        self.assertTrue((self.output / "FALLO.json").exists())
        self.assertFalse((self.output / "VERIFICADO.json").exists())

    def test_duplicate_keys_rejected(self):
        self.manifest.write_text('{"format":1,"format":2}', encoding="utf-8")
        with self.assertRaisesRegex(patcher.PatchError, "repetida"):
            self.apply()

    def test_cli_manifest_check_apply_and_no_manifest_overwrite(self):
        generated = self.folder / "generated.json"
        arguments = ["make-manifest", "--source", str(self.source),
                     "--patch", str(self.delta), "--target", str(self.target),
                     "--manifest", str(generated), "--base-description", "Synthetic base",
                     "--label", "Synthetic CLI test"]
        self.assertEqual(patcher.main(arguments), 0)
        original_manifest = generated.read_bytes()
        self.assertEqual(patcher.main(arguments), 1)
        self.assertEqual(generated.read_bytes(), original_manifest)
        self.assertEqual(patcher.main(["check", "--manifest", str(generated),
                                      "--source", str(self.source)]), 0)
        self.assertEqual(patcher.main(["apply", "--manifest", str(generated),
                                      "--source", str(self.source), "--output-dir", str(self.output),
                                      "--xdelta", str(self.xdelta), "--allow-experimental"]), 0)
        self.assertEqual((self.output / self.target.name).read_bytes(), self.target.read_bytes())

    def test_malformed_types_are_rejected_as_validation_errors(self):
        changes = [("status", []), ("status", {}), ("status", None),
                   ("label", []), ("base_description", {}), ("source", []),
                   ("patch", None), ("target", "invalid"), ("format", []),
                   ("platform", {})]
        for key, value in changes:
            with self.subTest(key=key, value=value):
                candidate = dict(self.data)
                candidate[key] = value
                with self.assertRaises(patcher.PatchError):
                    patcher.validate_manifest(candidate)
        for key, value in [("name", []), ("sha256", {}), ("size", True)]:
            with self.subTest(descriptor_key=key):
                candidate = dict(self.data)
                candidate["target"] = dict(self.data["target"], **{key: value})
                with self.assertRaises(patcher.PatchError):
                    patcher.validate_manifest(candidate)

    def test_cli_invalid_manifest_is_not_written(self):
        for index, label in enumerate(("", "   ")):
            generated = self.folder / f"invalid_{index}.json"
            self.assertEqual(patcher.main([
                "make-manifest", "--source", str(self.source), "--patch", str(self.delta),
                "--target", str(self.target), "--manifest", str(generated),
                "--base-description", "Synthetic", "--label", label]), 1)
            self.assertFalse(generated.exists())

    def test_cli_reserved_target_is_not_written(self):
        reserved = self.folder / "FALLO.json"
        reserved.write_bytes(b"synthetic target")
        generated = self.folder / "invalid_reserved.json"
        self.assertEqual(patcher.main([
            "make-manifest", "--source", str(self.source), "--patch", str(self.delta),
            "--target", str(reserved), "--manifest", str(generated),
            "--base-description", "Synthetic", "--label", "Synthetic"]), 1)
        self.assertFalse(generated.exists())

    def assert_change_detected_after_xdelta(self, changed_path, message):
        real_run = subprocess.run

        def run_then_change(*args, **kwargs):
            result = real_run(*args, **kwargs)
            with changed_path.open("ab") as stream:
                stream.write(b" ")
            return result

        with patch.object(patcher.subprocess, "run", side_effect=run_then_change):
            with self.assertRaisesRegex(patcher.PatchError, message):
                self.apply()
        self.assertTrue((self.output / "resultado.partial").exists())
        self.assertTrue((self.output / "FALLO.json").exists())
        self.assertFalse((self.output / "output.bin").exists())
        self.assertFalse((self.output / "VERIFICADO.json").exists())

    def test_source_change_during_xdelta_is_rejected(self):
        self.assert_change_detected_after_xdelta(self.source, "Base modificada")

    def test_patch_change_during_xdelta_is_rejected(self):
        self.assert_change_detected_after_xdelta(self.delta, "Parche modificado")

    def test_manifest_change_during_xdelta_is_rejected(self):
        self.assert_change_detected_after_xdelta(self.manifest, "Manifiesto modificado")


if __name__ == "__main__":
    unittest.main()

